class AjoutTrafic(QgsProcessingAlgorithm):
    """
    Algorithme pour ajouter l'information de trafic depuis une couche de points à une couche de
    noeuds.
    """

    # Constants used to refer to parameters and outputs. They will be
    # used when calling the algorithm from another algorithm, or when
    # calling from the QGIS console.

    OUTPUT = 'OUTPUT'
    INPUT = 'INPUT'
    RESEAU = 'RESEAU'
    MAXDIST = "MAXDIST"
    SPEED_FIELD = 'SPEED_FIELD'
    DIRECTION_FIELD = 'DIRECTION_FIELD'
    TRAFIC_PL = 'TRAFIC_PL'

    
    def name(self):
        """
        Returns the algorithm name, used for identifying the algorithm. This
        string should be fixed for the algorithm, and must not be localised.
        The name should be unique within each provider. Names should contain
        lowercase alphanumeric characters only and no spaces or other
        formatting characters.
        """
        return 'Ajouter le trafic'

    def displayName(self):
        """
        Returns the translated algorithm name, which should be used for any
        user-visible display of the algorithm name.
        """
        return self.tr(self.name())

    def group(self):
        """
        Returns the name of the group this algorithm belongs to. This string
        should be localised.
        """
        return self.tr(self.groupId())

    def groupId(self):
        """
        Returns the unique ID of the group this algorithm belongs to. This
        string should be fixed for the algorithm, and must not be localised.
        The group id should be unique within each provider. Group id should
        contain lowercase alphanumeric characters only and no spaces or other
        formatting characters.
        """
        return 'Formatage'

    def tr(self, string):
        return QCoreApplication.translate('Processing', string)

    def createInstance(self):
        return AjoutTrafic()
    
    def initAlgorithm(self, config):
        

        # We add the input vector features source. It can have any kind of
        # geometry.
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.INPUT,
                self.tr('Couche de trafic (point)'),
                [QgsProcessing.SourceType.TypeVectorPoint]
            )
        )
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.RESEAU,
                self.tr('Couche de réseau (lignes)'),
                [QgsProcessing.SourceType.TypeVectorLine]
            )
        )
        self.addParameter(QgsProcessingParameterField(self.DIRECTION_FIELD, 
                                                      self.tr("Colonne nom"),
                                                      parentLayerParameterName=self.RESEAU,
                                                      optional= False))
        
        self.addParameter(QgsProcessingParameterField(self.SPEED_FIELD, 
                                                      self.tr("Colonne trafic"), 
                                                      parentLayerParameterName=self.INPUT,
                                                      optional=False))
        self.addParameter(QgsProcessingParameterField(self.TRAFIC_PL, 
                                                       self.tr("Colonne trafic poids lourds (si existe)"), 
                                                       parentLayerParameterName=self.INPUT,
                                                       optional=True))
       
        
        self.addParameter(
            QgsProcessingParameterNumber(
                self.MAXDIST, 
                self.tr("Distance maximum entre les entités"),
                type=QgsProcessingParameterNumber.Double,
                defaultValue=0.1))

        # We add a feature sink in which to store our processed features (this
        # usually takes the form of a newly created vector layer when the
        # algorithm is run in QGIS).
        self.addParameter(
            QgsProcessingParameterFeatureSink(
                self.OUTPUT,
                self.tr('Output layer')
            )
        )

    def processAlgorithm(self, parameters, context, feedback):
        """
        Here is where the processing itself takes place.
        """

        # Retrieve the feature source and sink. The 'dest_id' variable is used
        # to uniquely identify the feature sink, and must be included in the
        # dictionary returned by the processAlgorithm function.
        source = self.parameterAsVectorLayer(parameters, self.INPUT, context)
        reseau = self.parameterAsVectorLayer(parameters, self.RESEAU, context)
        
        max_dist  = self.parameterAsDouble(parameters, self.MAXDIST, context)  # tolérance en unités de la couche
        field_trafic = self.parameterAsString(parameters, self.SPEED_FIELD, context)
        field_nom = self.parameterAsString(parameters, self.DIRECTION_FIELD, context)
        field_pl = self.parameterAsString(parameters, self.TRAFIC_PL, context)

        
        new_layer = source.materialize(QgsFeatureRequest().setFilterFids(source.allFeatureIds()))
        
        #Vérification
        pr = new_layer.dataProvider()
        existing = set(new_layer.fields().names())
        to_add =[]
        if 'pos_key' not in existing:
            to_add = [           
              QgsField('pos_key', QVariant.String)            
                  ]
        
        #to_add = [QgsField('pos_key', QVariant.String) if 'pos_key' not in existing]
        if to_add:
            pr.addAttributes(to_add)
            new_layer.updateFields()
            feedback.pushInfo(f"Added:, {[f.name() for f in to_add]}")
        else:
            feedback.pushInfo("Rien à ajouter")
        
        print(new_layer.fields().names())
        idx_key = new_layer.fields().indexOf('pos_key')
        
        features = list(new_layer.getFeatures())
        new_layer.startEditing()

        precision=6
        groups = {}
        for feat in features:
            geom = feat.geometry()
            pt = geom.asPoint()  
            key = f"{round(pt.x(), precision)}_{round(pt.y(), precision)}"
            new_layer.changeAttributeValue(feat.id(), idx_key, key)
            groups.setdefault(key, []).append(feat)
        
            
        new_layer.commitChanges()
        
        aggregates = [
            {
                'aggregate': 'mean',
                'delimiter': ',',
                'input': field_trafic,
                'length': 11,
                'name': field_trafic,
                'precision': 2,
                'sub_type': 0,
                'type': 6,  # Double
                'type_name': 'double'
            }
        ]

        if field_pl:
            aggregates.append({
                'aggregate': 'sum',
                'delimiter': ',',
                'input': field_pl,
                'length': 11,
                'name': field_pl,
                'precision': 2,
                'sub_type': 0,
                'type': 6,
                'type_name': 'double'
            })
        cpt_aggre = processing.run("native:aggregate", 
                       {'INPUT': new_layer,
                        'GROUP_BY':'geom_to_wkb($geometry)',
                        'AGGREGATES':aggregates,
                        'OUTPUT':'memory:compteurs_moyennes'
                        },  context=context, feedback=feedback)['OUTPUT']
        feedback.pushInfo(str(cpt_aggre.featureCount()))
        # for feat in source.getFeatures():
        #     geom =feat.geometry()
        #     pt = geom.asPoint()  
            
        result = processing.run("native:joinbynearest", 
                       {'INPUT':reseau,'INPUT_2': cpt_aggre,
                        'FIELDS_TO_COPY':[],
                        'DISCARD_NONMATCHING':False,
                        'PREFIX':'','NEIGHBORS':1,
                        'MAX_DISTANCE':max_dist,'OUTPUT': 'memory:'}
                       , context=context, feedback=feedback)['OUTPUT']
        
        idx_trafic = result.fields().indexOf(field_trafic)
        #idx_nom = result.fields().indexOf(field_nom)
    
        feats = {f.id(): f for f in result.getFeatures()}
    
        def endpoints(fid):
            # Trouve les points de début et de fin
            geom = feats[fid].geometry()
            line = geom.asMultiPolyline()[0] if geom.isMultipart() else geom.asPolyline()
            return (line[0], line[-1])
    
        # index des noeuds : {coord arrondie: [fid, fid, ...]}
        vertex_index = {}
        for fid in feats.keys():
            for pt in endpoints(fid):
                key = (round(pt.x(), precision), round(pt.y(), precision))
                vertex_index.setdefault(key, []).append(fid)
    
        queue = [fid for fid, f in feats.items() if f[field_trafic] not in (None, 'NULL')]
    
        result.startEditing()
    
        while queue:
            current_fid = queue.pop(0)
            current_val = feats[current_fid][field_trafic]
            current_nom = feats[current_fid][field_nom]
    
            for pt in endpoints(current_fid):
                key = (round(pt.x(), precision), round(pt.y(), precision))
                neighbors = vertex_index.get(key, [])
    
                if len(neighbors) > 2:
                    continue  #vraie intersection -> on ne propage pas à travers ce noeud
    
                for n_fid in neighbors:
                    if n_fid == current_fid:
                        continue
                    n_feat = feats[n_fid]
    
                    if n_feat[field_trafic] not in (None, 'NULL'):
                        continue  # déjà une valeur, on ne l'écrase pas
                    if n_feat[field_nom] != current_nom:
                        continue  # nom différent donc pas la même route
    
                    result.changeAttributeValue(n_fid, idx_trafic, current_val)
                    n_feat.setAttribute(idx_trafic, current_val)  
                    queue.append(n_fid)
    
        result.commitChanges()
        
        
        
        
        
        (sink, dest_id) = self.parameterAsSink(
        parameters, self.OUTPUT, context,
        result.fields(), result.wkbType(), result.sourceCrs()
        )
        for feat in result.getFeatures():
            sink.addFeature(feat, QgsFeatureSink.FastInsert)
        # Return the results of the algorithm. In this case our only result is
        # the feature sink which contains the processed features, but some
        # algorithms may return multiple feature sinks, calculated numeric
        # statistics, etc. These should all be included in the returned
        # dictionary, with keys matching the feature corresponding parameter
        # or output names.
        return {self.OUTPUT: dest_id}

